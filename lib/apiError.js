// ตัวช่วยกลางสำหรับทุก catch ในหลังบ้าน — เขียนบันทึกแล้วตอบผู้ใช้ในที่เดียว
//
// 🔑 กฎกลางอยู่ในสกิล `pharmacy-web-logic` ข้อ 31 (บันทึกของเซิร์ฟเวอร์)
//
// ปัญหาของเดิม — ทุกไฟล์เขียน console.error('[api]', e) เหมือนกันหมด
//   ① ป้ายเป็น [api] ทุกจุด เปิดบันทึกมาแล้วแยกไม่ออกว่าพังที่เส้นทางไหน วิธีไหน
//   ② ส่ง Error ทั้งก้อนเข้า console โดยไม่ปิดบัง เลขผู้ป่วยที่ฐานใส่มาเองจะหลุดออกไป
//   ③ เขียนกระจาย 29 จุด แล้วมีจุดที่ลืม จุดนั้นจะเงียบตลอดกาล
//
// เทียบกับห้องยา — เหมือนคนไข้แพ้ยาแล้วไม่มีใครจดว่าแพ้ตัวไหน
// รู้แค่ว่าแพ้ ครั้งหน้าก็ยังไม่รู้ว่าต้องเลี่ยงอะไร
import { NextResponse } from 'next/server';
import { maskHn, errParts, safeErrLine } from './maskHn';

/** ข้อความมีตัวอักษรไทยไหม — ใช้แยกว่าเป็นข้อความที่ตั้งใจเขียนให้คนอ่าน */
const เป็นภาษาไทย = (s) => /[฀-๿]/.test(s);

/**
 * เขียนบันทึกแล้วตอบผู้ใช้ — ใช้แทนทุก catch ในหลังบ้าน
 *
 * @param {string} where เส้นทางกับวิธี เช่น 'returns.POST' — ใช้ค้นในบันทึกภายหลัง
 * @param {unknown} e ข้อผิดพลาดที่จับได้
 * @param {string} fallback ข้อความไทยที่จะให้เภสัชกรเห็นเมื่อข้อความจริงเป็นภาษาช่าง
 * @param {number} [status] รหัสสถานะ ปกติ 500
 */
export function apiFail(where, e, fallback, status = 500) {
  const p = errParts(e);
  const เนื้อ = maskHn(p.body);

  // 🚨 ต้องปิดบังก่อนเขียนเสมอ — บันทึกเก็บอยู่นอกโรงพยาบาล
  //    ข้อความที่ฐานข้อมูลสร้างเองมีเลขผู้ป่วยประกอบอยู่ในตัว
  console.error('[' + where + '] ' + safeErrLine(e));
  if (e instanceof Error && e.stack) console.error(maskHn(e.stack));

  // 🚨 ข้อความจากฐานเป็นภาษาช่าง มีชื่อตาราง ชื่อคอลัมน์ ชื่อกฎอยู่ข้างใน
  //    ส่งกลับทั้งดุ้นแล้วเภสัชกรอ่านไม่รู้เรื่อง และคนที่จะเจาะเว็บได้แผนผังฐานฟรี
  //    ส่วนข้อความไทยที่เราตั้งใจโยนเอง (เช่น "จำนวนต้องมากกว่า 0") ส่งต่อได้

  // 🚨🔴 ต้องปิดบังฝั่งที่ส่งกลับด้วย ไม่ใช่ปิดบังแค่ตอนเขียนบันทึก
  //    ข้อความที่ฐานสร้างเองมีตัวอักษรไทยปนได้ (ชื่อ รพ.สต. · ชื่อผู้บันทึก ที่อยู่ในกฎของตาราง)
  //    มีไทยแม้ตัวเดียว ทางนี้จะส่งข้อความดิบกลับทั้งดุ้น พร้อมเลขผู้ป่วยที่ติดมาในข้อความ
  //    ไปโผล่บนหน้าจอผู้ใช้ = รูรั่วอีกทางที่การปิดบังฝั่งบันทึกกันไม่ถึง
  //    (scripts/api-fail-proof.mjs จับได้ตอนเขียนรอบแรก)
  //    ข้อความไทยที่เราโยนเองไม่มีเลข 4 หลักขึ้นไปสักข้อความ จึงไม่มีอะไรถูกปิดบังผิดตัว
  //    🚨 รหัสของฐานไม่ต้องส่งถึงเภสัชกร เป็นภาษาช่างล้วน · เก็บไว้ในบันทึกพอ
  const msg = เป็นภาษาไทย(p.body) ? เนื้อ : fallback;

  return NextResponse.json({ error: msg }, { status });
}

/**
 * เขียนบันทึกอย่างเดียว ไม่ตอบกลับ — ใช้กับงานเบื้องหลังที่ล้มแล้วไม่ควรทำให้ทั้งคำขอพัง
 * เช่น เขียนร่องรอยการแก้ไข หรือส่งเมล ที่ล้มแล้วงานหลักยังต้องเดินต่อ
 *
 * @param {string} where เส้นทางกับวิธี
 * @param {unknown} e ข้อผิดพลาดที่จับได้
 */
export function apiWarn(where, e) {
  console.error('[' + where + '] (ไม่ขวางงานหลัก) ' + safeErrLine(e));
}
