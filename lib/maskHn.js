// ปิดบังเลขผู้ป่วยก่อนเขียนลงบันทึกของเซิร์ฟเวอร์
//
// 🔑 กฎกลางอยู่ในสกิล `pharmacy-web-logic` ข้อ 31 (บันทึกของเซิร์ฟเวอร์)
//
// ทำไมต้องมี — บันทึกของ Cloudflare เก็บอยู่นอกโรงพยาบาล
// ข้อความผิดพลาดที่ฐานข้อมูลสร้างเองมีเลขผู้ป่วยประกอบอยู่ในตัวข้อความ
// ไม่ใช่สิ่งที่เราตั้งใจใส่ แต่ผลลัพธ์เหมือนกันคือเลขจริงไปค้างอยู่บนเครื่องคนอื่น
//
//   Error: มีผู้ป่วย HN 14820 ที่ใช้งานอยู่แล้ว
//   duplicate key value violates unique constraint ... (hn)=(9999001)
//
// 🚨 แยกเป็นไฟล์ของตัวเอง ห้ามรวมกับ apiError.js
//    เพราะไฟล์นั้น import next/server ซึ่งชุดทดสอบที่รันด้วย node ตรง ๆ เรียกไม่ได้
//
// 🚨 เว็บนี้ยังไม่มีใครกรอก HN จริงสักแถว (ตรวจ 2 ก.ย. 2569 — 218 แถว HN ว่างหมด)
//    แต่ช่องมีอยู่และกรอกได้ทุกเมื่อ ต้องมีตัวนี้ก่อนเปิดบันทึกเสมอ
//    เปิดก่อนแล้วค่อยทำ = ข้อมูลผู้ป่วยไหลออกตั้งแต่นาทีแรก

/**
 * ปิดบังเลขที่อาจเป็น HN ในข้อความ
 * @param {string} s ข้อความดิบจากข้อผิดพลาด
 * @returns {string} ข้อความที่แทนเลขผู้ป่วยด้วย ***
 */
export function maskHn(s) {
  if (s == null) return '';
  return String(s)
    // ① เลขที่ตามหลังคำว่า HN — จับก่อนเพราะรูปแบบชัดที่สุด
    //    รับทั้ง "HN 14820" · "HN14820" · "hn: 14820" · "(hn)=(14820)"
    // 🚨 ห้ามใส่ \b ปิดท้าย hn — "HN14820" ตัว N ติดกับ 1 ซึ่งเป็นอักขระคำทั้งคู่
    //    จึงไม่มีขอบเขตคำให้จับ แล้วเลขจะหลุด (ชุดทดสอบจับได้ตอนเขียนรอบแรก)
    .replace(/\bhn\s*[:=)(]*\s*([0-9]+)/gi, 'HN ***')
    // ② เลขล้วนตั้งแต่ 4 หลักขึ้นไปที่ลอยอยู่ในข้อความ
    //    HN ของที่นี่เป็นตัวเลขล้วน 4-7 หลัก
    //
    // 🚨 ตัวตรวจหน้าหลังสำคัญมาก — กันไม่ให้ไปโดน
    //    เลขบรรทัด (route.js:2026) · รหัสสุ่มที่ปนตัวอักษร (a1b2c3d4) ·
    //    รหัสยาที่ต่อกับตัวอักษร (L690901-01) · เลขเวอร์ชัน (0.16.3.0)
    .replace(/(?<![0-9a-zA-Z_.\-:/])[0-9]{4,}(?![0-9a-zA-Z_.\-:/])/g, '***');
}

/**
 * ปิดบังทั้งก้อน รวม stack trace — ใช้ตอนเขียนบันทึก
 * @param {unknown} v ค่าอะไรก็ได้
 * @returns {string}
 */
export function maskAny(v) {
  if (v == null) return '';
  if (typeof v === 'string') return maskHn(v);
  try {
    return maskHn(JSON.stringify(v));
  } catch (e) {
    return maskHn(String(v));
  }
}

/**
 * แยกสิ่งที่ถูกโยนมาเป็น 2 ส่วน — รหัสของฐาน กับ เนื้อความ
 *
 * 🚨🔴 กฎกลาง `pharmacy-web-logic` ข้อ 31 กับดักที่ 4 — สั่งให้เว็บที่ทำข้อนี้แล้วกลับมาแก้
 *
 * `supabase-js` **ไม่ได้โยน `Error`** แต่โยนก้อนข้อมูลธรรมดา
 * `{ message, code, details, hint }` · เขียน `String(e)` จะได้ `"[object Object]"`
 * **ร้องแล้วอ่านไม่รู้เรื่อง = ไร้ประโยชน์พอ ๆ กับเงียบ** แต่หลอกให้คิดว่าทำเสร็จแล้ว
 * (ME-DRP เจอของจริงมาแล้ว 2 ก.ย. 2569)
 *
 * 🚨 ต้องแยก `code` ออกมาต่างหาก ห้ามรวมอยู่ในเนื้อความ
 *    รหัสของ Postgres เป็นเลข 5 ตัว (`23505` บันทึกซ้ำ · `42P01` ไม่มีตาราง · `23503` ผิดกฎความสัมพันธ์)
 *    ถ้ารวมไว้ในก้อนเดียว **ตัวปิดบังจะมองว่าเป็นเลขผู้ป่วยแล้วกลบทิ้ง**
 *    ทั้งที่เป็นกุญแจดอกแรกของการไล่บั๊ก (ทดสอบแล้ว `รหัส 23505` กลายเป็น `รหัส ***` จริง)
 *
 * ⚠️ ทุก route ในเว็บนี้ดึง `.message` ออกมาก่อนโยนอยู่แล้วครบทุกจุด
 *    ตัวนี้จึงเป็น **ตาข่ายกันอนาคต** — วันหน้ามีคนเขียน `throw res.error` ตรง ๆ ก็ยังอ่านออก
 *
 * @param {unknown} e สิ่งที่ถูกโยนมา
 * @returns {{ code: string, body: string }}
 */
export function errParts(e) {
  if (e == null) return { code: '', body: '' };
  if (e instanceof Error) return { code: '', body: e.message };
  if (typeof e === 'string') return { code: '', body: e };

  if (typeof e === 'object') {
    const ส่วน = [e.message, e.details, e.hint].filter(Boolean).map(String);
    const code = e.code ? String(e.code) : '';
    if (ส่วน.length || code) return { code: code, body: ส่วน.join(' · ') };
  }

  try { return { code: '', body: JSON.stringify(e) }; }
  catch (err) { return { code: '', body: String(e) }; }
}

/** ประกอบกลับเป็นข้อความเดียว — ใช้ตอนอยากได้ทั้งก้อนโดยไม่ต้องปิดบัง */
export function errText(e) {
  const p = errParts(e);
  if (p.code && p.body) return 'รหัส ' + p.code + ' · ' + p.body;
  return p.code ? 'รหัส ' + p.code : p.body;
}

/**
 * ข้อความที่ปลอดภัยพอจะเขียนลงบันทึก — ปิดบังเนื้อความ แต่คงรหัสฐานไว้ให้อ่านได้
 * @param {unknown} e
 * @returns {string}
 */
export function safeErrLine(e) {
  const p = errParts(e);
  const เนื้อ = maskHn(p.body);
  if (p.code && เนื้อ) return 'รหัส ' + p.code + ' · ' + เนื้อ;
  return p.code ? 'รหัส ' + p.code : เนื้อ;
}
