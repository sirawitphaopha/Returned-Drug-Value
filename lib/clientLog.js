//
// 🔑 กฎกลาง `pharmacy-web-logic` ข้อ 31 · ยกแนวคิดมาจาก ME-DRP (`lib/clientLog.ts`)
//
// ทำไมเว็บที่มีหลังบ้านแล้วยังต้องมีตัวนี้
//   Workers Logs เก็บเฉพาะสิ่งที่เกิดบนเครื่องของ Cloudflare
//   แต่ `catch {}` ที่อยู่ในโค้ดฝั่งเบราว์เซอร์ทำงานบนเครื่องของเภสัชกร
//   ไม่เคยผ่าน worker เลยสักครั้ง → เปิดบันทึกมาก็ไม่เห็นอะไร
//
// ตัวอย่างที่เคยเงียบสนิทในเว็บนี้
//   โหลดร่างจากเซิร์ฟเวอร์ล้ม  → แถบล็อตค้างไม่ขึ้น โดยไม่มีใครรู้ว่าล้ม
//   โหลดคลังยาใหม่ล้ม          → แก้ชื่อยาที่เว็บอื่นแล้วที่นี่ยังเห็นของเก่า
//   โหลดการตั้งค่าล้ม          → รายชื่อ รพ.สต. หายไปเฉย ๆ
//
// 🚨 ปิดบังเลขผู้ป่วยก่อนร้องเสมอ — คอนโซลของเบราว์เซอร์ก็เป็นที่ที่คนอื่นเปิดดูได้
//    (ยืมเครื่อง · ส่วนขยายที่อ่านคอนโซล · ภาพหน้าจอที่ส่งต่อกัน)
import { safeErrLine } from './maskHn';

/**
 * ผู้ใช้เสียประโยชน์จริง — ของที่ควรได้ไม่ได้ หรือได้ของเก่าโดยไม่รู้ตัว
 *
 * 🚨 ห้ามใช้กับสิ่งที่ล้มได้ตามปกติ ไม่งั้นคอนโซลจะเต็มไปด้วยเสียงรบกวน
 *    แล้วเรื่องที่สำคัญจริงจะจมหายไป
 *
 * @param {string} where ชื่อฟังก์ชันกับงานที่ทำ เช่น 'loadServerDrafts (โหลดร่างจากเซิร์ฟเวอร์)'
 * @param {unknown} e สิ่งที่จับได้จาก catch
 */
export function logFail(where, e) {
  try { console.error('[' + where + '] ' + safeErrLine(e)); } catch (err) {}
}

/**
 * ล้มได้ตามปกติ ไม่ต้องตกใจ — แต่ยังอยากเห็นตอนไล่บั๊ก
 * เช่น ที่เก็บในเครื่องเต็ม · เบราว์เซอร์โหมดส่วนตัว · ผู้ใช้ปิดสิทธิ์บางอย่าง
 *
 * @param {string} where
 * @param {unknown} e
 */
export function logWarn(where, e) {
  try { console.warn('[' + where + '] ' + safeErrLine(e)); } catch (err) {}
}
