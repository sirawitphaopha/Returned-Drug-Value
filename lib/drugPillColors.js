// คืน { color, label } ถ้ายาตัวนี้มีสีเม็ดกำหนดไว้ · ไม่มีคืน null
// 🚨 รับได้ทั้งยาที่มาจาก API ของเว็บยาคืน (pillColor/pillColorHex)
//    และยาที่อ่านจาก Supabase ตรง ๆ แบบ ME-DRP (pill_color/pill_color_hex)
export function pillColorOf(drug) {
  if (!drug) return null;
  const label = String(drug.pillColor || drug.pill_color || '').trim();
  if (!label) return null;
  const hex = String(drug.pillColorHex || drug.pill_color_hex || '').trim();
  return { label: label, color: hex || COLOR_HEX[label] || '#414a44' };
}
