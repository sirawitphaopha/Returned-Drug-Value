import { s, sx, kb } from '../helpers';

// ปุ่มล้างการเรียง — ใช้ร่วมกันทั้งหน้าประวัติ · รายการ Lot · คลังยา
// พี่กันสั่ง 4 ก.ย. 2569: "ปุ่มล้างค่าที ตอนที่เราเรียงไปเเล้ว"
//
// 🚨 โผล่เฉพาะตอนมีการเรียงอยู่จริง — ไม่งั้นเป็นปุ่มที่กดแล้วไม่เกิดอะไร
//    (กฎเดียวกับปุ่มล้างตัวกรองของหน้ารายการ Lot ที่พี่กันสั่งไว้ 26 ส.ค. 2569)
// 🚨 สีโทนร้อน (แดงอิฐบนพื้นแดงจาง) เพราะเป็นปุ่มที่ทำให้ของบนจอเปลี่ยนทันที
//    ต้องสะดุดตาพอที่จะรู้ว่ากดแล้วเกิดอะไร (พี่กันสั่ง 4 ก.ย. 2569 "ขอสีเด่น โทนร้อน")
//    ใช้โทนเดียวกับปุ่มลบและปุ่มล้างรายการ ซึ่งเป็นตระกูล "กดแล้วของหาย" เหมือนกัน
// 🚨 คนละปุ่มกับ "ล้างค่าทั้งหมด" ที่ล้างคำค้นกับตัวกรอง
//    การเรียงกับการกรองเป็นคนละเรื่อง ล้างพร้อมกันแล้วจะเสียของที่ยังอยากได้อยู่
export function renderSortClear(o) {
  if (!o || !o.on) return null;
  return (
    <div {...kb(o.clear)} aria-label="ล้างการเรียงลำดับ" className="hv-bg-fbe tap"
      title={'กลับไปเรียงตามค่าเริ่มต้น' + (o.label ? ' (ตอนนี้เรียงตาม ' + o.label + ')' : '')}
      style={s('display:inline-flex;align-items:center;gap:5px;flex:none;padding:8px 14px;border:1px solid rgba(194,84,60,.32);border-radius:999px;background:#fdf1ed;font:600 12.5px/1.75 Sarabun,sans-serif;color:#c2543c;cursor:pointer;white-space:nowrap')}>
      <span aria-hidden="true" style={s('font-size:13px;line-height:1')}>↺</span>
      ล้างการเรียง
    </div>
  );
}
