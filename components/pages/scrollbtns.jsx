import React from 'react';
import { s, sx, kb, Z } from '../helpers';

// ═══════════════════════════════════════════════════════════════════════════
//  ปุ่มขึ้นบนสุด / ลงล่างสุด — ตัวกลางตัวเดียว ใช้ทั้งมือถือและคอม
// ═══════════════════════════════════════════════════════════════════════════
//
//  พี่กันเคาะ 10 ก.ย. 2569 หลังดูมอคอัป 3 แบบ (docs/mockups/scroll-btns-2026-09-10.html)
//    "ไม่เอา ก เพราะมันจะมองปุ่มนั้นเป็นปุ่มเรียง" · "ควรเอาแบบ ค"
//    "ปุ่มทั้งสองปุ่มจะไม่แสดงเสมอนะ
//     ถ้าบนสุด จะแสดงปุ่มลงสุด แต่ถ้าระหว่างตอนที่เลื่อน จะแสดงสองปุ่ม
//     และถ้าลงสุดจะแสดงแค่ปุ่มบนสุดเท่านั้น"
//    "เอาระบบนี้ไปใช้กับเว็บเดสก์ท็อปด้วย แต่ถ้าเอาเมาส์ไปชี้ มันจะเปลี่ยนเป็นสีเข้ม"
//
//  โจทย์ตั้งต้นคือ "ปุ่มต้องไม่บังเนื้อหา" จึงคุมด้วยสองชั้นพร้อมกัน
//    ชั้นที่ 1  ปุ่มไหนโผล่ — ตามตำแหน่งที่เลื่อนอยู่ (บนสุด · ระหว่างทาง · ล่างสุด)
//    ชั้นที่ 2  ชัดแค่ไหน  — เพิ่งเลื่อน = ชัดเต็มตา · หยุดอ่านเกิน 1.5 วิ = จางลง
//
// 🚨 กล่องครอบต้องเป็น pointer-events:none ปุ่มข้างในถึงเป็น auto
//    ไม่งั้นช่องว่างระหว่างปุ่มสองอันจะกลืนการกดของสิ่งที่อยู่ข้างใต้
//    (หน้าประวัติมีปุ่ม แก้/ลบ อยู่ตรงนั้นพอดี — เป็นเหตุผลทั้งหมดที่ต้องรื้อแบบเดิม)
//
// 🚨 ตำแหน่งปุ่มตายตัวเสมอ — ขึ้นอยู่บน ลงอยู่ล่าง ห้ามให้ปุ่มเลื่อนมาแทนที่กัน
//    ปุ่มที่ขยับตำแหน่งตามสถานการณ์ทำให้ตาต้องไล่หาใหม่ทุกครั้ง
//
// 🚨 ปุ่มที่ไม่ควรแสดงต้องเป็น pointer-events:none ด้วย ไม่ใช่แค่จางจนมองไม่เห็น
//    ปุ่มใสที่ยังกดได้ = กับดักที่หาสาเหตุไม่ได้เลย
export function renderScrollBtns(V) {
  if (!V.jumpOn) return null;

  const กลม = 'width:44px;height:44px;border-radius:50%;background:#2f7d5d;color:#fff;'
    + 'display:flex;align-items:center;justify-content:center;cursor:pointer;'
    + 'box-shadow:0 6px 18px rgba(30,36,32,.28);font:700 17px Sarabun,sans-serif';

  const ปุ่ม = (โผล่, วาง, ทำ, ป้าย, รูป) => (
    <div {...kb(ทำ)} className="hv-teal jump-btn" title={ป้าย} aria-label={ป้าย}
      aria-hidden={โผล่ ? undefined : 'true'} tabIndex={โผล่ ? 0 : -1}
      style={sx(กลม + ';position:absolute;left:0;' + วาง, {
        opacity: โผล่ ? (V.jumpAwake ? 1 : 0.3) : 0,
        transform: โผล่ ? 'scale(1)' : 'scale(.7)',
        pointerEvents: โผล่ ? 'auto' : 'none'
      })}>{รูป}</div>
  );

  return (
    <div aria-hidden={V.jumpUp || V.jumpDown ? undefined : 'true'}
      style={sx('position:fixed;right:16px;width:44px;height:96px;pointer-events:none', {
        bottom: 'calc(var(--bottombar, 0px) + 16px)', zIndex: Z.float
      })}>
      {ปุ่ม(V.jumpUp, 'top:0', V.jumpToTop, 'เลื่อนขึ้นบนสุด', '↑')}
      {ปุ่ม(V.jumpDown, 'bottom:0', V.jumpToBottom, 'เลื่อนลงล่างสุด', '↓')}
    </div>
  );
}
