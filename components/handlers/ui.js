// ตัวช่วยทั่วไป: เก็บลงเครื่อง · ข้อความเด้ง · ตัวเลขที่นับขึ้น
// คัดจากมอคอัป (บรรทัด 957–1004) ตัดเฉพาะส่วนที่เก็บรายการที่บันทึกแล้วลงเครื่อง
// เพราะยอด KPI เก่าค้างบนจอแย่กว่ารอโหลดนิดหน่อย
import { LS, writeLS } from '../helpers';

export function uiActions(app) {
  // เก็บเฉพาะร่างที่ยังไม่บันทึก กับธีม — ที่เหลืออยู่บนเซิร์ฟเวอร์
  // 🚨 batchId ต้องเก็บคู่กับร่างเสมอ — ถ้าส่งไม่สำเร็จแล้วผู้ใช้รีเฟรชหน้าเว็บ
  // (คนทั่วไปทำแบบนี้เวลาเว็บค้าง) แล้ว batchId หาย ระบบกันบันทึกซ้ำจะไม่ทำงาน
  // กดบันทึกใหม่ = ข้อมูลเข้าฐานสองชุด มูลค่า KPI เบิ้ล
  // hn/source/date เก็บด้วย ไม่งั้นเปิดกลับมาแล้วยาอยู่ครบแต่ HN หาย
  app.persist = (patch) => {
    app.setState(patch, () => {
      const st = app.state;
      // 🚨 โหมดดูตัวอย่างห้ามเขียนทับร่างจริงในเครื่องเด็ดขาด
      // หน้าบันทึกมีล็อตตัวอย่างค้างอยู่ ถ้าปล่อยให้เขียนลง localStorage
      // ยาที่พี่กันกรอกค้างไว้จริงก่อนกดเปิดโหมดจะถูกทับหายถาวร กู้ไม่ได้
      if (st.demo) return;
      writeLS(LS.draft, {
        v: 1,
        rows: st.rows,
        batchId: st.batchId,
        hn: st.hn,
        source: st.source,
        sourceTouched: st.sourceTouched,
        pcuSite: st.pcuSite,
        date: st.date
      });
      writeLS(LS.dark, st.dark ? 1 : 0);
    });
  };

  // ── ฟอนต์ตัวอักษรอังกฤษและตัวเลข (พี่กันสั่ง 27 ส.ค. 2569) ────────────────
  // 'mono' = Roboto Mono ตัวเลขกว้างเท่ากันทุกตัว · 'thai' = ใช้ Sarabun เหมือนภาษาไทย
  // 🚨 เขียนตัวแปร CSS ตรง ๆ ที่ราก ไม่เก็บใน state ของ React
  //    เพราะฟอนต์ต้องเปลี่ยนทั้งเว็บทันที รวมส่วนที่ยังไม่ถูกวาดใหม่
  // 🚨 โหมด 'thai' ต้องชี้กลับไปที่ Sarabun ห้ามตั้งเป็นค่าว่าง
  //    ไม่งั้นประโยค font-family พังทั้งบรรทัด ตัวอักษรกลายเป็นฟอนต์ระบบ
  app.applyEnFont = (mode) => {
    if (typeof document === 'undefined') return;
    document.documentElement.style.setProperty(
      '--font-en',
      mode === 'thai' ? 'var(--font-sarabun)' : 'var(--font-mono)'
    );
  };

  app.setEnFont = (mode) => {
    app.setState({ enFont: mode }, () => {
      app.applyEnFont(mode);
      writeLS(LS.enFont, mode);
    });
  };

  // สลับแท็บ — หน้าประวัติกับหน้าสรุปดึงข้อมูลจากเซิร์ฟเวอร์ เลยต้องสั่งโหลดตอนเข้า
  // (มอคอัปไม่มีขั้นนี้เพราะข้อมูลอยู่ในเครื่องอยู่แล้ว)
  app.goScreen = (name) => {
    app.setState({ screen: name }, () => {
      // 🚨 เด้งกลับบนสุดทุกครั้งที่สลับแท็บ (พี่กันแจ้งบั๊ก)
      // พื้นที่เลื่อนเป็นก้อนเดียวใช้ร่วมกันทุกหน้า ไม่ได้ถูกสร้างใหม่ตอนสลับ
      // ตำแหน่งที่เลื่อนค้างจากหน้าเดิมเลยติดมาด้วย เปิดหน้าสรุปมาแล้วอยู่กลางหน้า
      // มองไม่เห็นตัวเลขใหญ่ซึ่งเป็นของสำคัญที่สุดของหน้านั้น
      //
      // ต้องรีเซ็ต 2 จังหวะ ครั้งเดียวไม่พอ — หน้าประวัติกับหน้าสรุปตอนเพิ่งเข้ายังไม่มีข้อมูล
      // เนื้อหาเลยสั้น พอข้อมูลมาถึงแล้วเนื้อหายืดยาวขึ้น เบราว์เซอร์จะดึงตำแหน่งเลื่อนกลับมา
      // (ทำงานคู่กับ overflow-anchor:none ที่พื้นที่เลื่อนใน shell.jsx)
      app.toTop();

      if (name === 'history') app.loadHistory();
      if (name === 'summary') { app.loadSummary(); app.loadTopReturned(); }
    });
  };

  // เด้งพื้นที่เลื่อนหลักกลับบนสุด — เรียกซ้ำในเฟรมถัดไปด้วยเผื่อเนื้อหายังวาดไม่เสร็จ
  app.toTop = () => {
    const set = () => { const sc = app.scrollRef && app.scrollRef.current; if (sc) sc.scrollTop = 0; };
    set();
    if (typeof requestAnimationFrame === 'function') requestAnimationFrame(set);
  };

  app.savedTotal = () =>
    app.state.rows.reduce((s, r) => s + (r.disposition === 'reuse' ? r.price * r.qty : 0), 0);

  app.lostTotal = () =>
    app.state.rows.reduce((s, r) => s + (r.disposition === 'destroy' ? r.price * r.qty : 0), 0);

  app.animateTo = (target) => {
    if (app._raf) cancelAnimationFrame(app._raf);
    const from = app.state.animSaved;
    if (Math.abs(target - from) < 0.005) { app.setState({ animSaved: target }); return; }
    const t0 = performance.now();
    const step = (t) => {
      const k = Math.min(1, (t - t0) / 420);
      const e = 1 - Math.pow(1 - k, 3);
      app.setState({ animSaved: from + (target - from) * e });
      if (k < 1) app._raf = requestAnimationFrame(step);
    };
    app._raf = requestAnimationFrame(step);
  };

  // 🚨🚨 ข้อความแจ้งต้องค้างจนกว่าผู้ใช้จะกดปิดเอง — ทั้งสำเร็จและไม่สำเร็จ
  //
  // พี่กันเคาะ 26 ส.ค. 2569: "ไม่หายทั้งจะสำเร็จหรือไม่สำเร็จ ต้องกดยืนยันหรือปิดเอง
  //                          และอันนี้กดเอนเทอร์แล้วไม่ไปนะ ต้องเมาส์ชี้เท่านั้น"
  //
  // ของเดิมหายเองใน 2 วินาที ใช้เวลาเดียวกันหมดไม่ว่าจะ "บันทึกสำเร็จ"
  // หรือ "อ่านประวัติไม่สำเร็จ" และตั้ง pointer-events:none ไว้จนแตะไม่ได้
  //
  // กัดจริงมาแล้ว 2 ครั้ง
  //   25 ส.ค. — กดยืนยันแก้ล็อตแล้วโดนตีกลับ ข้อความบอกเหตุผลหายก่อนอ่านทัน
  //             ดูเหมือนปุ่มเสีย เสียเวลาไปพักใหญ่
  //   26 ส.ค. — "โหลดข้อมูลจากเซิร์ฟเวอร์ไม่สำเร็จ" ผุดแล้วหาย
  //             พี่กันถามว่า "สรุปมันโหลดสำเร็จไหมเนี่ย" ซึ่งตอบไม่ได้เพราะข้อความหายไปแล้ว
  //
  // 🚨 แยกกันคนละแบบ — พี่กันเคาะรอบสอง 26 ส.ค. 2569 หลังเห็นของจริง
  //    "ข้อความที่สำเร็จ เรานึกว่าตอนกดบันทึกสุดท้าย ไม่ใช่แค่ยิบย่อยแบบนี้
  //     งั้นเอาออก แล้วให้กดปิดเฉพาะผิดพลาด"
  //
  //    สำเร็จ  → หายเองใน 4 วินาที ไม่มีปุ่มปิด
  //             เพราะ "เพิ่ม Metformin +30.00" เด้งทุกครั้งที่กดเพิ่มยา
  //             กรอก 30 ตัวก็ต้องกดปิด 30 ครั้ง ซึ่งกวนกว่าเดิม
  //             4 วินาทีนานพอให้อ่านทัน (ของเดิม 2 วินาทีสั้นไป)
  //
  //    ผิดพลาด → ค้างจนกว่าจะกดปิด ไม่มีตัวจับเวลาเด็ดขาด
  //             อันนี้คือตัวที่กัดพี่กันมาแล้ว 2 ครั้ง
  //             25 ส.ค. กดยืนยันแก้ล็อตแล้วโดนตีกลับ ข้อความหายก่อนอ่านทัน ดูเหมือนปุ่มเสีย
  //             26 ส.ค. "โหลดข้อมูลไม่สำเร็จ" ผุดแล้วหาย จนถามว่าสรุปโหลดสำเร็จไหม
  //
  // 🚨 ห้ามใส่ตัวจับเวลาให้ข้อความผิดพลาดเด็ดขาด ไม่ว่าจะกี่วินาทีก็ตาม
  app.toast = (text, value, ok) => {
    if (app._toastTimer) clearTimeout(app._toastTimer);
    const good = ok !== false;
    app.setState({ toast: { text: text, value: value, ok: good } });
    if (navigator.vibrate) { try { navigator.vibrate(12); } catch (e) {} }
    if (good) app._toastTimer = setTimeout(() => app.setState({ toast: null }), 4000);
  };

  // 🚨 ปิดได้ด้วยการคลิกเมาส์เท่านั้น — ห้ามผูกกับคีย์บอร์ด (พี่กันสั่งตรง ๆ)
  //    เพราะผู้ใช้กด Enter รัว ๆ ตอนกรอกยา (Enter สองจังหวะคือเส้นทางหลัก)
  //    ถ้า Enter ปิดข้อความได้ ข้อความจะถูกปิดทิ้งโดยไม่ได้ตั้งใจก่อนอ่านทัน
  //    ซึ่งกลับไปเป็นปัญหาเดิมที่เพิ่งแก้ไป
  app.closeToast = () => app.setState({ toast: null });
}
