import { maskHn, maskAny } from '../lib/maskHn.js';

let ผ่าน = 0, ตก = 0;

/** ข้อความหลังปิดบังต้องไม่มีเลขที่ห้ามหลุด */
function ต้องไม่มี(ชื่อ, input, ห้ามมี) {
  const out = maskHn(input);
  const พบ = [].concat(ห้ามมี).filter((x) => out.includes(x));
  if (pass(พบ.length === 0, ชื่อ, input, out, 'ห้ามเหลือ ' + [].concat(ห้ามมี).join(' · '))) return;
}

/** ข้อความหลังปิดบังต้องยังมีของที่ไม่ควรโดนแตะ */
function ต้องยังมี(ชื่อ, input, ต้องเหลือ) {
  const out = maskHn(input);
  const ขาด = [].concat(ต้องเหลือ).filter((x) => !out.includes(x));
  pass(ขาด.length === 0, ชื่อ, input, out, 'ต้องเหลือ ' + [].concat(ต้องเหลือ).join(' · '));
}

function pass(ok, ชื่อ, input, out, เกณฑ์) {
  if (ok) { ผ่าน++; console.log('  OK  ' + ชื่อ); return true; }
  ตก++;
  console.log('  X   ' + ชื่อ);
  console.log('        เข้า   ' + input);
  console.log('        ออก    ' + out);
  console.log('        เกณฑ์  ' + เกณฑ์);
  return false;
}

