/**
 * ของที่ตัวตรวจต้องเจอ ถ้าไม่เจอให้พังเสียงดัง ห้ามเงียบ
 *
 * 🚨 นี่คือหัวใจของการแก้รอบนี้ — เดิมหาไม่เจอแล้วคืนค่าว่าง
 *    ตัวตรวจก็เอาค่าว่างไปรายงานว่า "0px" หรือ "ไม่มีปัญหา"
 *
 * @param {Record<string, unknown>} ของที่ต้องเจอ  ชื่อ → ค่าที่ได้จากหน้าจอ
 */
export function mustFind(ของที่ต้องเจอ) {
  const หาไม่เจอ = Object.entries(ของที่ต้องเจอ)
    .filter(([, v]) => v === null || v === undefined || v === false || v === 0 || v === '(ไม่เจอ)')
    .map(([k]) => k);

  if (หาไม่เจอ.length) {
    console.error('');
    console.error('🔴🔴 ตัวตรวจหาของบนหน้าจอไม่เจอ — หยุดก่อน อย่าเชื่อผลที่ออกมา');
    console.error('   หาไม่เจอ: ' + หาไม่เจอ.join(' · '));
    console.error('');
    console.error('   สาเหตุที่เป็นไปได้');
    console.error('     1. ข้อความบนหน้าจอถูกเปลี่ยน → มาแก้ scripts/lib/ui-text.mjs');
    console.error('     2. หน้าจอยังโหลดไม่เสร็จ → เพิ่มเวลารอ');
    console.error('     3. ของนั้นถูกเอาออกจากเว็บจริง ๆ → แก้ตัวตรวจให้เลิกหา');
    console.error('');
    process.exit(1);
  }
}

