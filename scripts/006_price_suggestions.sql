-- 006 — ช่องเก็บ "ราคาที่ระบบเสนอ" ให้เภสัชกรกดเลือก
--
-- ที่มา: พี่กันไม่อยากยุ่งกับไฟล์ HIS เอง สั่งว่า "เธอใส่ราคาเลย เเล้วเราจะกดเลือกเอง"
--        แคลร์เลยจับคู่ให้ล่วงหน้าแล้วเขียนผลลงตารางนี้
--
-- 🚨 กติกาความปลอดภัยที่ต้องรักษาไว้
--    ยาที่จับคู่ได้ "ชัวร์" (เจอตัวเดียว + ความแรงตรง) → ใส่ unit_price ลงไปเลย
--    ยาที่ "ไม่ชัวร์"                                  → unit_price ต้องเป็น 0 เท่านั้น
--                                                        แล้วแนบตัวเลือกไว้ใน suggestions
--
--    เหตุผล: ถ้าใส่ราคาที่อาจผิดลงไปแล้วเภสัชกรมองข้าม ตัวเลข KPI จะผิดแบบเงียบ ๆ
--            แต่ถ้าปล่อยเป็น 0 ระบบจะกันไม่ให้บันทึกยาตัวนั้นตั้งแต่หน้าบันทึกเลย
--            (ดู app.blockNoPrice) = ไม่มีทางได้ข้อมูลผิดเข้าฐาน
--
--    ตัวอย่างจริงที่เกือบพลาด: Amoxicillin + Clavulanic acid 500 + 125 mg
--    ระบบจับไปเจอ "Amoxicillin 250 mg = 2 ฿" ซึ่งเป็นยาเดี่ยว ราคาต่างกันหลายเท่า
--
-- หมายเหตุ: ไฟล์นี้เก็บเฉพาะการแก้โครงตาราง
--           ตัวข้อมูลราคา 417 แถวไม่ได้เก็บใน repo เพราะเป็นราคายาภายในของโรงพยาบาล
--           และ repo นี้เปิดสาธารณะ · สร้างใหม่ได้เสมอจากไฟล์ HIS ผ่านหน้า "นำเข้าราคาจาก HIS"

alter table mr_drug_price
  add column if not exists needs_check  boolean not null default false,
  add column if not exists suggestions  jsonb   not null default '[]'::jsonb;

comment on column mr_drug_price.needs_check is
  'true = จับคู่กับ HIS ไม่ชัวร์ รอเภสัชกรกดเลือก · ราคาต้องเป็น 0 จนกว่าจะยืนยัน';
comment on column mr_drug_price.suggestions is
  'ราคาที่ระบบเสนอ [{name, price, unit}] ให้กดเลือกในหน้าจัดการราคา';

-- ดัชนีเบา ๆ ไว้กรองแท็บ "ต้องเลือก" ในหน้าจัดการราคา
create index if not exists mr_drug_price_check_idx on mr_drug_price (needs_check) where needs_check;
